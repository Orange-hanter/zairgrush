#!/usr/bin/env bash
# Единственный гейт качества для кода оркестратора: линт, типы, тесты.
#
# Почему одним скриптом, а не тремя командами в голове оператора: гейт —
# это то, что петля запускает МЕХАНИЧЕСКИ (§5.2), и он обязан быть одним
# вызовом с одним кодом возврата. Разные проверки, запускаемые по памяти,
# — это проверки, которые однажды не запустят.
#
# Порядок не случаен: сначала дешёвое и локальное (линт), потом типы,
# потом дорогой прогон тестов. Падение на первом шаге экономит остальные.
set -euo pipefail
cd "$(dirname "$0")"

VENV="${SWARM_VENV:-.venv}"
RUFF="$VENV/bin/ruff"
MYPY="$VENV/bin/mypy"

if [[ ! -x "$RUFF" || ! -x "$MYPY" ]]; then
    echo "нет инструментов проверки в $VENV" >&2
    echo "создать: uv venv $VENV && uv pip install --python $VENV ruff mypy" >&2
    exit 3
fi

echo "== линт =="
"$RUFF" check swarm/ tests/ mutate.py

echo "== типы (strict) =="
"$MYPY"

echo "== тесты =="
# -B и очистка кэша: скомпилированный байткод переживает откат исходника
# и заставляет Python исполнять СТАРЫЙ код. На мутационном аудите это уже
# давало ложный вывод «мутация не поймана» — тест проходил по кэшу.
find . -name __pycache__ -type d -exec rm -rf {} + 2>/dev/null || true
PYTHONDONTWRITEBYTECODE=1 python3 -B -m pytest -q

echo "== всё зелёное =="
