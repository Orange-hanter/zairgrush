"""Живость петли по флоку `state.lock` — без импорта остального роя.

Отдельным модулем, а не методом `SwarmState`, потому что вопрос «идёт ли
прогон» задаёт не только петля: автодополнение оболочки (`clitab`)
спрашивает его на каждый Tab по всем известным стендам, и тянуть ради
этого `state` (а с ним `obs` и `git rev-parse` на импорте) нельзя.
Один источник ответа на оба случая: расхождение «доска говорит жив,
Tab говорит мёртв» было бы хуже, чем отсутствие подсказки.
"""
import fcntl
import pathlib


def probe(lock_path: pathlib.Path) -> bool:
    """Держит ли кто-то блокировку состояния.

    Не по pid из файла: pid переиспользуется системой, и мёртвый прогон
    изредка «оживал» чужим процессом с тем же номером. Флок отвечает
    точно: захватился — держать некому.
    """
    try:
        fh = lock_path.open("r")
    except OSError:
        return False           # файла нет — блокировку никто не брал
    try:
        fcntl.flock(fh, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        return True            # занят — на том конце живой оркестратор
    else:
        fcntl.flock(fh, fcntl.LOCK_UN)
        return False
    finally:
        fh.close()
