"""Режим траты денег: один вопрос — есть ли неявный потолок у вызова.

Потолков в петле два разных вида, и путать их дорого.

ЯВНЫЙ потолок — число, которое оператор написал в `swarm.toml`. Он
остаётся в силе ВСЕГДА, при любом режиме: настройка, которая молча
перестаёт действовать, — худший из отказов этого инструмента (весь
закрытый список ключей в `cli.py` существует ровно потому, что опечатка
однажды включила умолчание, а оператор был уверен в своей настройке).
Стенд с `total_budget_usd = 120` в коммите обязан остановиться на 120.

НЕЯВНЫЙ потолок — умолчание кода, которого никто не просил. Такой у
петли был один и висел на самой дорогой роли: ревьюер звался с
`--max-budget-usd 1.0`, даже если в конфиге о деньгах не было ни слова.
Он и срабатывал: «ревьюер обрублен по бюджету» — штатный диагноз петли,
а на плечах E9 (2026-08-24) обрыв по потолку вызова съел по раунду у
обоих плеч и был записан крахом. Обрубленный вызов не экономит деньги, а
выбрасывает уже потраченные: работа сделана, отчёта нет.

Режимы:

  money_bin (умолчание) — неявных потолков нет вовсе. Явные действуют.
  capped                — прежнее поведение: у ревьюера умолчание $1.

Название — денежный чан Скруджа: в нём не считают монеты, но чан всё же
принадлежит владельцу, и потому режим объявляется вслух на старте
прогона и в `doctor`. Тихий режим «без потолка» — то, как получают
неожиданный счёт.
"""
from __future__ import annotations

from typing import Any

MODES = frozenset({"money_bin", "capped"})
DEFAULT_MODE = "money_bin"

# Неявные умолчания режима `capped` — ровно те, что были в коде до
# появления режимов. Список закрыт: новый неявный потолок обязан
# появиться здесь, а не в argv роли, иначе он снова станет невидимым.
CAPPED_DEFAULTS: dict[str, float] = {"review_budget_usd": 1.0}


def mode(config: dict[str, Any]) -> str:
    """Режим траты. Незнакомое значение — не умолчание, а отказ.

    Тот же довод, что у `executor_engine`: опечатка в имени режима не
    имеет права молча включить противоположную политику денег.
    """
    raw = config.get("spending", DEFAULT_MODE)
    value = str(raw)
    if value not in MODES:
        msg = (f"spending = {raw!r} — неизвестный режим траты. "
               f"Допустимо: {', '.join(sorted(MODES))}")
        raise ValueError(msg)
    return value


def call_cap(config: dict[str, Any], key: str) -> float | None:
    """Потолок ОДНОГО вызова роли: число или None, если потолка нет.

    Порядок разбора — единственное содержательное решение модуля:
    явно заданное значение читается ДО режима. Иначе `money_bin`
    отменял бы настройку, которую оператор написал руками и закоммитил,
    а это ровно то поведение, из-за которого в петле появился закрытый
    список ключей.
    """
    explicit = config.get(key)
    if explicit is not None:
        # Ноль — осмысленное значение «не ставить потолок», а не пустое:
        # `0` в `--max-budget-usd` обрубил бы вызов немедленно.
        return float(explicit) or None
    if mode(config) == "capped":
        return CAPPED_DEFAULTS.get(key)
    return None


def budget_flags(config: dict[str, Any], key: str) -> list[str]:
    """Аргументы `--max-budget-usd` для argv роли — или ничего.

    Отсутствие флага и есть «нет потолка»: CLI без него не обрубает
    вызов, а подставлять заведомо большое число значило бы врать
    журналу — в конверте появился бы потолок, которого не просили.
    """
    cap = call_cap(config, key)
    return ["--max-budget-usd", str(cap)] if cap is not None else []


class BudgetExhaustedError(RuntimeError):
    """Потолок ПРОГОНА пробит посреди хода: следующий вызов не уходит.

    Не «провал роли» и не квота: ловится петлей отдельно и сводится к
    тому же терминальному исходу, что у проверки между раундами
    (`budget_stop` в loop). Цифры несёт с собой — журналу нужны факты,
    а не повторное чтение метрик.
    """

    def __init__(self, spent: float, budget: float, role: str = "") -> None:
        self.spent = spent
        self.budget = budget
        self.role = role
        super().__init__(
            f"бюджет прогона исчерпан: ${spent} из ${budget}"
            + (f", вызов роли {role}" if role else "")
        )


def guard(config: dict[str, Any], state: Any, role: str = "",
          cap_key: str = "") -> None:
    """Страж потолка прогона ВОКРУГ каждого вызова LLM.

    Межраундовая проверка в loop видела потолок только между итерациями,
    и один ход пробивал его на любую величину: g1nt сжёг $2.75 при
    потолке $0.70, потому что внутри хода (исполнитель, ревьюер, повторы)
    останавливать было некому. Здесь две проверки одной функцией:

    ДО диспетча (задан cap_key): потраченное плюс потолок предстоящего
    вызова — худшая честная оценка его цены — против бюджета. Потолка
    роли нет (money_bin) — оценка ноль, и решает только записанный факт.
    ПОСЛЕ записи цены (cap_key не задан): потраченное против бюджета,
    чтобы СЛЕДУЮЩИЙ вызов того же хода уже не ушёл.
    """
    budget = run_budget(config)
    if budget is None:
        return
    spent = state.total_spend()
    estimate = call_cap(config, cap_key) if cap_key else None
    if spent + (estimate or 0.0) >= budget:
        raise BudgetExhaustedError(spent, budget, role)


def run_budget(config: dict[str, Any]) -> float | None:
    """Потолок ПРОГОНА. Неявного не бывает ни в одном режиме.

    Останов прогона по деньгам — решение владельца о том, сколько стоит
    цель, и выдумать его за него нельзя ни в ту, ни в другую сторону.
    Функция существует, чтобы это правило было записано один раз и его
    можно было прочитать, а не выводить из трёх мест в `loop.py`.
    """
    raw = config.get("total_budget_usd")
    return float(raw) if raw else None


# Все ключи потолков вызова, какие петля знает. Строка отчёта человеку
# перечисляет ДЕЙСТВУЮЩИЕ потолки, а не умолчания режима, — иначе она
# врала бы в обе стороны сразу: «потолков нет» при явно заданном числе и
# «потолок $1» при явном нуле, который его снимает.
CALL_CAP_KEYS = ("review_budget_usd", "executor_budget_usd",
                 "plan_budget_usd")


def effective_caps(config: dict[str, Any]) -> dict[str, float]:
    """Потолки вызовов, которые РЕАЛЬНО уедут в argv ролей."""
    out = {}
    for key in CALL_CAP_KEYS:
        cap = call_cap(config, key)
        if cap is not None:
            out[key] = cap
    return out


def headline(config: dict[str, Any], spent: float) -> str:
    """Одна строка для человека на старте прогона и в `doctor`.

    Режим без потолков обязан назвать себя сам: молчание здесь — это как
    раз тот случай, когда счёт объясняют постфактум. Но называется
    именно действующее положение дел, а не имя режима: `money_bin` с
    одним явно заданным потолком — это прогон С потолком, и сказать
    «потолков нет» значило бы соврать о собственной настройке оператора.
    """
    total = run_budget(config)
    caps = effective_caps(config)
    if caps:
        named = ", ".join(f"{k.replace('_budget_usd', '')} ${v}"
                          for k, v in sorted(caps.items()))
        tail = f"потолки вызовов: {named}"
        if mode(config) == DEFAULT_MODE:
            tail += " (режим денежного чана, но потолки заданы явно)"
    else:
        tail = "потолков вызова НЕТ — режим денежного чана"
    head = ("бюджет прогона: не задан" if total is None
            else f"бюджет прогона: ${total}")
    return f"{head}, потрачено ${spent}; {tail}"
