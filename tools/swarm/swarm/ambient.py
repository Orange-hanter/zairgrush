"""Фоновый замер: фактор бросается жребием в ОБЫЧНОЙ работе.

Зачем это существует. Парный замер на стендах — точный и дорогой
инструмент: два клона, один фактор, одна задача. Он дал ответ по плечу
планировщика E9 и по движкам E13, и он же дважды не дал ответа по плечу
исполнителя. Причина названа в 06-доке: на ОДНОЙ задаче счётчик раундов
доминируется тем, запустил ли исполнитель `cargo fmt`, а честная парная
очередь на десять задач стоит порядка $130 — цена, которую владелец
платит за один вопрос. Хуже цены другое: задачу для замера выбираю я, и
выбираю под ожидаемый признак. Так и получилось с s2ky — признак был
взят из прошлого прогона и не воспроизвёлся.

Фоновый замер устраняет обе беды сразу. Фактор включается не «на
прогон», а на КАЖДУЮ ЗАДАЧУ по жребию; работа при этом идёт настоящая и
всё равно была бы оплачена. Через несколько недель обычных прогонов
накапливается несмещённая выборка, которой никто не выбирал.

Чем он ХУЖЕ парного, и это надо сказать прямо: выборка НЕПАРНАЯ. В
плечах оказываются разные задачи, а не одна задача дважды, поэтому
дисперсия между задачами не вычитается и на малом n фоновый замер
слабее. Он берёт своё числом наблюдений, а не их качеством, и потому
инструмент разбора отказывается объявлять победителя ниже названного
порога, а не печатает процент от трёх задач.

Устройство, три решения.

1. Жребий ДЕТЕРМИНИРОВАН по задаче: плечо есть функция от (сид, фактор,
   id задачи), а не от порядка вызовов. Значит повтор той же задачи
   попадает в то же плечо (реплей остаётся реплеем), а разбор может
   пересчитать назначения из одних id — не доверяя журналу, который сам
   же и проверяет.

2. Фактор ОДИН. Два случайных фактора в одном прогоне дают выборку, в
   которой эффекты неразделимы, и это не осторожность, а арифметика.

3. Явно закреплённый флаг и фоновый жребий по тому же фактору —
   ОТКАЗ на старте, а не тихая победа одного из них. Иначе в журнал
   писалось бы «плечо выбрано жребием» о прогоне, где оно было
   прибито гвоздём.
"""
from __future__ import annotations

import hashlib
from typing import Any

# Факторы, которые умеют участвовать в фоновом замере. Ключ — имя
# фактора, значение — что именно он переключает в блоке [experiments].
# Список закрыт: фактор, которого здесь нет, петля не бросает жребием, и
# опечатка не превращается в тихое «фоновый замер выключен».
FACTORS: dict[str, tuple[str, Any, Any]] = {
    # фактор: (ключ в [experiments], значение плеча ON, значение плеча OFF)
    "tester": ("tester", True, False),
    "memory_executor": ("memory", "executor", "off"),
    "memory_reviewer": ("memory", "reviewer", "off"),
    "memory_planner": ("memory", "planner", "off"),
    "skeleton": ("skeleton", True, False),
}


def factor(config: dict[str, Any]) -> str | None:
    """Имя фонового фактора или None. Незнакомое имя — отказ."""
    exp = config.get("experiments") or {}
    name = exp.get("ambient")
    if name is None:
        return None
    if name not in FACTORS:
        msg = (f"[experiments] ambient = {name!r} — такого фактора нет. "
               f"Допустимо: {', '.join(sorted(FACTORS))}")
        raise ValueError(msg)
    return str(name)


def conflict(config: dict[str, Any]) -> str | None:
    """Фоновый фактор, который вместе с тем прибит явно, — или None.

    Отказ, а не молчаливое старшинство: журнал, называющий жребием то,
    что задано гвоздём, портит не прогон, а ВЫБОРКУ — и портит молча,
    так что заметить это можно будет только по несходящимся числам через
    несколько недель.
    """
    name = factor(config)
    if name is None:
        return None
    key, _on, _off = FACTORS[name]
    exp = config.get("experiments") or {}
    if key in exp:
        return (f"[experiments] {key} задан явно ({exp[key]!r}) и он же "
                f"бросается жребием как ambient = {name!r}. Фоновый замер "
                f"писал бы в журнал выбор, которого не делал: убери одно "
                f"из двух")
    return None


def arm(config: dict[str, Any], task_id: str) -> str:
    """Плечо задачи: `on` или `off`. Чистая функция от сида и id.

    Хэш, а не `random`: жребий обязан быть пересчитываемым из одних
    только (сид, фактор, id). Тогда разбор не зависит от журнала, а
    реплей задачи попадает в то же плечо, что и первый прогон.
    """
    name = factor(config)
    if name is None:
        msg = "фонового фактора нет — плечо не определено"
        raise ValueError(msg)
    exp = config.get("experiments") or {}
    seed = str(exp.get("ambient_seed", ""))
    raw = f"{seed}|{name}|{task_id}".encode()
    digest = hashlib.sha256(raw).digest()
    return "on" if digest[0] % 2 else "off"


def overlay(config: dict[str, Any], task_id: str) -> dict[str, Any] | None:
    """Конфиг задачи с разыгранным фактором, либо None если замера нет.

    Возвращается КОПИЯ: общий конфиг прогона не мутируется, иначе плечо
    одной задачи протекало бы в следующую — самый неприятный из
    возможных дефектов здесь, потому что он не падает, а тихо смешивает
    выборку.
    """
    name = factor(config)
    if name is None:
        return None
    key, on_value, off_value = FACTORS[name]
    chosen = on_value if arm(config, task_id) == "on" else off_value
    out = dict(config)
    out["experiments"] = dict(config.get("experiments") or {})
    out["experiments"][key] = chosen
    return out


def facts(config: dict[str, Any], task_id: str) -> dict[str, Any]:
    """Что записать в журнал и метрику, чтобы разбор был возможен.

    Пишется и фактор, и плечо, и СИД: без сида запись не проверяема, а
    непроверяемая телеметрия замера — та же фольклорная цифра, что и
    процент от трёх задач.
    """
    name = factor(config)
    if name is None:
        return {}
    exp = config.get("experiments") or {}
    key, on_value, _off = FACTORS[name]
    return {"ambient_factor": name, "ambient_arm": arm(config, task_id),
            "ambient_seed": exp.get("ambient_seed"),
            "ambient_key": key, "ambient_on_value": on_value}
