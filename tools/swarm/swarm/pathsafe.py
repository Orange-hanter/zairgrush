"""Санитизация путей и имён файлов: единая точка перед записью.

Три находки про path traversal сошлись сюда: task['id'] шёл в имена
файлов логов без проверки, а chat-fill собирал путь записи из `paths`
задачи без проверки на выход за пределы корня. Правило одно: всё, что
пришло из спецификации задачи, проходит через эти хелперы ДО того, как
станет именем файла или путём записи.
"""

from __future__ import annotations

import hashlib
import pathlib
from typing import Any

# Верхняя граница длины ОТДЕЛЬНОГО компонента имени. Лимит имени файла у
# ОС — 255 байт, а к id в имени лога ещё приклеиваются суффиксы раунда
# (`-i3-executor-shadow.jsonl`) — запас держит их всех.
_MAX_COMPONENT = 120

# Замена полностью пустому результату: «пустое» id у всех таких задач
# слилось бы в один файл лога без всякого идентификатора.
_EMPTY_NAME = "no-id"


def safe_filename(name: Any) -> str:
    """Имя файла из недоверенного значения (task['id'] и т.п.).

    Остаются буквы (включая нелатиницу), цифры, '.', '_' и '-'; прочие
    символы — разделители, пробелы, слэши — заменяются на '_', так что
    запись не уйдёт из каталога, который выбрал вызывающий. Точки
    допустимы внутри имени (версии вида v1.2), но ведущие точки режутся
    целиком: имя из одних точек ('.', '..', '...') — служебные записи
    каталога, а ведущая точка делает файл скрытым — логам это не нужно.
    Длинный id обрезается с хвостом-хэшем: голый обрезок коллизировал
    бы между собой, а неограниченное имя уперлось бы в лимит ОС.
    Коллизии имён для логов некритичны: метка задачи читается внутри
    файла, а не из его имени.
    """
    text = "".join(ch if ch.isalnum() or ch in "._-" else "_" for ch in str(name))
    text = text.lstrip(".")
    if not text:
        text = _EMPTY_NAME
    if len(text) > _MAX_COMPONENT:
        digest = hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]
        text = f"{text[: _MAX_COMPONENT - 13]}~{digest}"
    return text


def short_digest(name: Any) -> str:
    """Короткий дайджест СЫРОГО значения — страховка от коллизий
    санитайзера: 'a/b' и 'a_b' сходятся в одно имя, их дайджесты — нет.

    Именно сырого, не санитизированного: вся разница, которую выкинул
    safe_filename, живёт в дайджесте. Восемь hex-символов (32 бита) —
    для десятков задач в прогоне коллизия практически исключена, а имя
    лога остаётся коротким и читаемым.
    """
    return hashlib.sha256(str(name).encode("utf-8")).hexdigest()[:8]


def escapes_root(root: pathlib.Path, rel: str | pathlib.PurePath) -> bool:
    """True, если путь уводит запись за пределы корня состояния.

    Проверка в два слоя. Лексический (быстрый, понятная диагностика):
    абсолютный путь или '..' — отказ. Разрешённый (ловит симлинки):
    кандидат и корень резолвятся ОБА — иначе корень вроде /tmp на macOS
    (симлинк на /private/tmp) давал бы ложный отказ честным путям, — и
    кандидат обязан остаться внутри разрешённого корня. Лексический слой
    не снимается: он отсекает '..' раньше резолва и даёт честный ответ
    на пути, которых на диске ещё нет.
    """
    pure = pathlib.PurePath(rel)
    if pure.is_absolute() or ".." in pure.parts:
        return True
    resolved_root = root.resolve()
    resolved = (root / rel).resolve()
    return not resolved.is_relative_to(resolved_root)
